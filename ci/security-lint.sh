#!/usr/bin/env bash
# security-lint: offline checks for Istio security manifests, meant for CI.
# Usage: ci/security-lint.sh <dir or file>...
#
# Two layers, both without a cluster:
#  1. istioctl analyze --use-kube=false --all-namespaces on the files.
#  2. Static checks (yq -> JSON, jq) for mistakes the API server and
#     istioctl analyze accept, each one reproduced in the lab:
#     - RequestAuthentication with no AuthorizationPolicy that requires a
#       token for the same target: requests without a token are accepted;
#     - principals without a trust domain ("ns/<ns>/sa/<sa>"): never match;
#     - principals naming a ServiceAccount that is not in the analyzed set
#       (wrong namespace or name): never match. Only checked when the set
#       contains ServiceAccounts; Gateway (<name>-istio) and waypoint
#       (<name>) service accounts generated by istiod count as known;
#     - ALLOW with an empty rule ({}): allows every request;
#     - DENY with notPrincipals/notNamespaces: denies every other caller;
#     - DENY rule with HTTP attributes and no port: also denies all TCP
#       traffic in its scope (istiod only warns on apply);
#     - L7 attributes in a policy enforced by ztunnel (ambient namespace,
#       selector or namespace-wide): fails safe into deny-everything;
#     - ztunnel policy naming callers other than the waypoint in an ambient
#       namespace that uses a waypoint: ztunnel sees the waypoint identity;
#     - PeerAuthentication portLevelMtls without a selector (rejected by the
#       API server) or on a port that is not a container port of the
#       selected workloads (e.g. the Service port): never applies;
#     - ServiceEntry HTTP port sent to targetPort 443 without a
#       DestinationRule that originates TLS for it: plain HTTP to a TLS port.
# Not detectable offline: plain-text callers still in production traffic
# (use mtls/plaintext-inventory.sh against the cluster before STRICT).
# Analyze the whole set that is applied together: cross-resource checks only
# see the files they are given. Exits 1 on any finding.
set -uo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
export PATH="${REPO_ROOT}/bin:${PATH}"

if [ "$#" -eq 0 ]; then
  echo "usage: $0 <dir or file>..." >&2
  exit 2
fi
for tool in istioctl yq jq; do
  command -v "${tool}" >/dev/null || { echo "missing ${tool}: run tools/install-cli.sh (jq: install it)" >&2; exit 2; }
done

files=()
for arg in "$@"; do
  if [ -d "${arg}" ]; then
    while IFS= read -r f; do files+=("${f}"); done \
      < <(find "${arg}" -type f \( -name '*.yaml' -o -name '*.yml' \) | sort)
  else
    files+=("${arg}")
  fi
done
if [ "${#files[@]}" -eq 0 ]; then
  echo "no YAML files found in: $*" >&2
  exit 2
fi

status=0

kfiles=()
for f in "${files[@]}"; do
  if [ "$(yq 'select(.kind == "IstioOperator") | .kind' "${f}" 2>/dev/null)" = "" ]; then kfiles+=("${f}"); fi
done
echo "== istioctl analyze --use-kube=false --all-namespaces (${#kfiles[@]} files)"
if [ "${#kfiles[@]}" -gt 0 ] && ! istioctl analyze --use-kube=false --all-namespaces "${kfiles[@]}" 2>&1; then
  status=1
fi

echo "== static security checks"
docs=""
for f in "${files[@]}"; do
  if ! one="$(yq -o=json -I=0 '.' "${f}" | jq -c --arg file "${f}" 'select(. != null) | {file: $file, doc: .}')"; then
    echo "ERROR ${f}: not parseable as YAML"
    status=1
    continue
  fi
  docs+="${one}"$'\n'
done

# shellcheck disable=SC2016 # jq program, not shell
findings="$(jq -r -s '
  def ns: .metadata.namespace // "default";
  def id: "\(.kind) \(ns)/\(.metadata.name)";
  def rules: (.spec.rules // []);
  def action: (.spec.action // "ALLOW");
  def ops: [rules[] | (.to // [])[] | .operation // {}];
  def sources: [rules[] | (.from // [])[] | .source // {}];
  def http_keys: ["hosts", "notHosts", "methods", "notMethods", "paths", "notPaths"];
  def has_l7:
    any(ops[]; (keys - (keys - http_keys)) | length > 0)
    or any(sources[]; has("requestPrincipals") or has("notRequestPrincipals"))
    or any(rules[] | (.when // [])[]; .key | startswith("request."));
  def selects($sel; $labels): ($sel | length) > 0 and ($sel | to_entries | all(.value == $labels[.key]));
  def targets: if .spec.targetRefs then [.spec.targetRefs[] | "\(.kind)/\(.name)"]
               elif .spec.selector then ["selector:\(.spec.selector.matchLabels | tojson)"]
               else ["namespace"] end;

  [ .[] | .doc ] as $docs
  | . as $all
  | ([ $docs[] | select(.kind == "Namespace") | {key: .metadata.name, value: (.metadata.labels // {})} ] | from_entries) as $nslabels
  | ([ $docs[] | select(.kind == "ServiceAccount") | "\(ns)/\(.metadata.name)" ]
     + [ $docs[] | select(.kind == "Gateway" and .spec.gatewayClassName == "istio") | "\(ns)/\(.metadata.name)-istio" ]
     + [ $docs[] | select(.kind == "Gateway" and .spec.gatewayClassName == "istio-waypoint") | "\(ns)/\(.metadata.name)" ]) as $identities
  | ([ $docs[] | select(.kind == "ServiceAccount") ] | length > 0) as $know_identities
  | [ $docs[] | select(.kind == "AuthorizationPolicy") ] as $aps
  | [ $all[] | .file as $file | .doc as $d
      | if $d.kind == "RequestAuthentication" then
          ($d | targets) as $t
          | if any($aps[]; (ns) == ($d | ns)
                 and ((targets == ["namespace"]) or ((targets - (targets - $t)) | length > 0))
                 and ((action == "ALLOW" and any(sources[]; has("requestPrincipals")))
                      or (action == "DENY" and any(sources[]; has("notRequestPrincipals")))
                      or any(rules[] | (.when // [])[]; .key == "request.auth.principal")))
            then empty
            else "\($file): \($d | id): no AuthorizationPolicy in the set requires a token for \($t | join(",")) (requestPrincipals): requests without a token are accepted"
            end
        elif $d.kind == "AuthorizationPolicy" then
          ( ($d | rules) | to_entries[] | select(.value == {}) | select(($d | action) == "ALLOW")
            | "\($file): \($d | id): rule #\(.key) is empty: an empty rule matches every request, so this ALLOW allows everything (deny by default is \"spec: {}\"; deny-all is action DENY)" ),
          ( [$d | sources[] | (.principals // []), (.notPrincipals // []) | .[]] | unique[] | . as $p
            | if test("^ns/") then
                "\($file): \($d | id): principal \"\($p)\" has no trust domain: principals are matched as <trust domain>/ns/<namespace>/sa/<service account>, this one never matches"
              elif $know_identities and test("^[^/*]+/ns/[^/*]+/sa/[^/*]+$") then
                ($p | capture("^[^/]+/ns/(?<n>[^/]+)/sa/(?<s>[^/]+)$")) as $c
                | if any($identities[]; . == "\($c.n)/\($c.s)") then empty
                  else "\($file): \($d | id): principal \"\($p)\" names no ServiceAccount of the analyzed set (\($c.n)/\($c.s)): it never matches"
                  end
              else empty end ),
          ( if ($d | action) == "DENY" and any($d | sources[]; has("notPrincipals") or has("notNamespaces")) then
              "\($file): \($d | id): DENY with notPrincipals/notNamespaces denies every caller that is not listed, including other mesh services and plain-text callers"
            else empty end ),
          ( if ($d | action) == "DENY" then
              ($d | rules) | to_entries[] | .key as $i
              | select(any((.value.to // [])[] | .operation // {};
                           ((keys - (keys - http_keys)) | length > 0) and (has("ports") or has("notPorts") | not)))
              | "\($file): \($d | id): DENY rule #\($i) uses HTTP attributes without a port: it also denies all TCP traffic in its scope (istiod only warns on apply)"
            else empty end ),
          ( ($nslabels[$d | ns] // {}) as $l
            | if $l["istio.io/dataplane-mode"] == "ambient" and ($d.spec.targetRefs == null) then
                ( if ($d | has_l7) then
                    "\($file): \($d | id): L7 attributes in a policy enforced by ztunnel (ambient namespace, \(if $d.spec.selector then "workload selector" else "namespace-wide" end)): ztunnel cannot evaluate them and the policy fails safe into denying everything it selects; attach it to the waypoint with targetRefs"
                  else empty end ),
                ( if $l["istio.io/use-waypoint"] != null and ($d | action) == "ALLOW" then
                    "\($d | ns)/\($l["istio.io/use-waypoint"])" as $wp
                    | [$d | sources[] | (.principals // [])[]] as $ps
                    | if ($ps | length) > 0 and any($ps[]; test("/ns/\($wp | split("/")[0])/sa/\($wp | split("/")[1])$") | not) then
                        "\($file): \($d | id): ztunnel policy names callers other than the waypoint in a namespace that uses the waypoint \"\($l["istio.io/use-waypoint"])\": traffic through the waypoint arrives with the waypoint identity and is refused, while traffic that skips the waypoint is allowed"
                      else empty end
                  else empty end )
              else empty end )
        elif $d.kind == "PeerAuthentication" and $d.spec.portLevelMtls != null then
          if $d.spec.selector == null then
            "\($file): \($d | id): portLevelMtls without a selector (the API server rejects it: portLevelMtls requires selector)"
          else
            [ $docs[] | select(.kind == "Deployment" and (ns) == ($d | ns))
              | select(selects($d.spec.selector.matchLabels // {}; .spec.template.metadata.labels // {}))
              | .spec.template.spec.containers[] | (.ports // [])[] | .containerPort | tostring ] as $cports
            | if ($cports | length) == 0 then empty
              else ($d.spec.portLevelMtls | keys[]) as $port
                | select(any($cports[]; . == $port) | not)
                | "\($file): \($d | id): portLevelMtls port \($port) is not a container port of the selected workloads (\($cports | unique | join(","))): it matches the workload port, not the Service port, so it never applies"
              end
          end
        elif $d.kind == "ServiceEntry" then
          ($d.spec.hosts // [])[] as $h
          | ($d.spec.ports // [])[] | select(.targetPort == 443 and ((.protocol // "") | ascii_upcase) == "HTTP") | .number as $p
          | if any($docs[]; .kind == "DestinationRule" and .spec.host == $h
                 and (((.spec.trafficPolicy.portLevelSettings // [])[] | select(.port.number == $p) | .tls.mode) // .spec.trafficPolicy.tls.mode // "" | IN("SIMPLE", "MUTUAL")))
            then empty
            else "\($file): \($d | id): port \($p) of \($h) is HTTP sent to targetPort 443 with no DestinationRule originating TLS (tls mode SIMPLE) for it: the request leaves in plain text to a TLS port (503 UC)"
            end
        else empty end ]
  | .[]' <<< "${docs}")"
jq_rc=$?
# Fail closed: a broken check must not look like a clean result.
if [ "${jq_rc}" -ne 0 ]; then
  echo "ERROR static checks could not run (jq exit ${jq_rc})"
  status=1
fi

if [ -n "${findings}" ]; then
  while IFS= read -r line; do echo "ERROR ${line}"; done <<< "${findings}"
  status=1
else
  echo "no security findings"
fi

[ "${status}" -eq 0 ] && echo "security-lint: PASS" || echo "security-lint: FAIL"
exit "${status}"
